// Generates docs/api.md from the route table in src/api/routes.ts, so the
// reference cannot drift from what the server actually exposes.
// `npm run docs:api` writes it; `npm run docs:api -- --check` fails if stale (used by tests).

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROUTES } from '../src/api/routes.js';
import { ROLE_PERMISSIONS, type Role } from '../src/control/auth.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'docs/api.md');

export function renderApiDocs(): string {
  const roles = (perm: string | null) => {
    if (perm === null) return 'public';
    if (perm === 'authenticated') return 'any valid token';
    return (Object.keys(ROLE_PERMISSIONS) as Role[]).filter((r) => ROLE_PERMISSIONS[r].has(perm as never)).join(', ');
  };
  const groups = new Map<string, typeof ROUTES[number][]>();
  for (const r of ROUTES) {
    const g = r.url.split('/')[5] ?? r.url.split('/')[3] ?? 'other';
    const key = r.url.includes(':tenant') ? (g || 'tenant') : 'platform';
    groups.set(key, [...(groups.get(key) ?? []), r]);
  }
  const lines = [
    '# Clearline HTTP API',
    '',
    '<!-- Generated by `npm run docs:api` from src/api/routes.ts. Do not edit by hand. -->',
    '',
    'All endpoints are JSON unless noted. Authenticate with `Authorization: Bearer <token>`. Tenant-scoped paths (`/api/v1/tenants/:tenant/...`) are authorized against the token\'s tenant before the handler runs; a token for another tenant receives `403 cross_tenant_denied`, and the attempt is audited in both tenants.',
    '',
    'Every response carries `X-Correlation-Id` (send your own to correlate client and server logs). Errors have the shape `{"error": {"code", "message", "details?"}, "correlation_id"}`.',
    '',
    '| Status | Meaning |',
    '|---|---|',
    '| 200 / 201 | Success / created |',
    '| 202 | Accepted for asynchronous processing (batches) or awaiting approval (breaking contract) |',
    '| 400 | Malformed request (unknown source, bad control totals, invalid filter) |',
    '| 401 | Missing, invalid or revoked token |',
    '| 403 | Role lacks the permission, or cross-tenant access |',
    '| 404 | Not found within your tenant |',
    '| 409 | State conflict (migration pending, version exists, rollback window closed) |',
    '| 422 | Rejected: invalid contract, unsafe migration, structurally invalid payload |',
    '',
    '## Operational endpoints',
    '',
    '| Method | Path | Auth | Description |',
    '|---|---|---|---|',
    '| GET | `/healthz` | public | Liveness: the process is up. |',
    '| GET | `/readyz` | public | Readiness: database reachable and no pending migrations (503 otherwise). |',
    '| GET | `/metrics` | `METRICS_TOKEN` bearer if set | Prometheus text format: HTTP, batch, row and auth counters; backlog, oldest queued age, freshness and live-worker gauges. |',
    '',
  ];
  for (const [g, rs] of groups) {
    lines.push(`## ${g === 'platform' ? 'Platform and identity' : g[0].toUpperCase() + g.slice(1)}`, '', '| Method | Path | Roles | Description |', '|---|---|---|---|');
    for (const r of rs) lines.push(`| ${r.method} | \`${r.url}\` | ${roles(r.perm)} | ${r.summary.replace(/\|/g, '\\|')} |`);
    lines.push('');
  }
  lines.push('## Examples', '',
    '```sh',
    'T=cl_dev_northwind_operator',
    '# Submit a CSV batch with control totals',
    'curl -sS -X POST "http://localhost:8080/api/v1/tenants/northwind/batches/csv?source=nw_medical_claims_csv&source_reported_at=2026-10-01T06:00:00Z" \\',
    '  -H "Authorization: Bearer $T" -H "Content-Type: text/csv" \\',
    '  -H \'X-Clearline-Control: {"record_count": 1000, "sums": {"paid_amount": "498911.75"}}\' --data-binary @claims.csv',
    '# Inspect it',
    'curl -sS -H "Authorization: Bearer $T" http://localhost:8080/api/v1/tenants/northwind/batches/<batch_id>',
    '# Reproducible filtered extract (same as_of + filters => same bytes and sha256)',
    'curl -sS -G -H "Authorization: Bearer cl_dev_northwind_reporter" http://localhost:8080/api/v1/tenants/northwind/extracts/claims/csv \\',
    '  --data-urlencode \'filters={"status":"PAID","service_date":{"gte":"2026-06-01","lte":"2026-08-31"}}\' --data-urlencode as_of=2026-10-19T21:00:00Z -D -',
    '```', '',
    'Extract responses include `X-Clearline-Export-Id`, `-Extract-Id`, `-Contract-Version`, `-As-Of`, `-Filters`, `-Row-Count`, `-Sha256`, `-Redacted-Fields` and `-Trust-Scope` headers. See `docs/examples/` for sample extracts and responses.', '');
  return lines.join('\n');
}

if (process.argv[1]?.endsWith('gen-api-docs.ts') || process.argv[1]?.endsWith('gen-api-docs.js')) {
  const doc = renderApiDocs();
  if (process.argv.includes('--check')) {
    const cur = readFileSync(OUT, 'utf8');
    if (cur !== doc) { console.error('docs/api.md is stale: run npm run docs:api'); process.exit(1); }
    console.log('docs/api.md is up to date');
  } else { writeFileSync(OUT, doc); console.log(`wrote ${path.relative(ROOT, OUT)} (${ROUTES.length} routes)`); }
  process.exit(0);
}
