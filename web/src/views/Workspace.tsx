import { useEffect, useState } from 'react';
import { download, enc, request, saveBlob, session, t } from '../lib/api';
import { count, ms } from '../lib/format';
import { useAction, useLoad } from '../lib/useLoad';
import { Async, Button, ErrorBox, Facts, Field, Grid, Json, Note, Page, Section, Signal, Table, Tag } from '../ui';

/* eslint-disable @typescript-eslint/no-explicit-any */
export function Workspace({ seed }: { seed: string | null }) {
  const catalog = useLoad((s) => request<any>('GET', t('/queries/catalog'), undefined, { signal: s }), []);
  const [question, setQuestion] = useState('');
  const [sql, setSql] = useState('');
  const [proposal, setProposal] = useState<any>(null);
  const [result, setResult] = useState<any>(null);
  const [execId, setExecId] = useState<string | null>(null);

  useEffect(() => {
    if (!seed) return;
    request<any>('GET', t(`/queries/proposals/${enc(seed)}`)).then((p) => { setProposal(p); setSql(p.validated_sql ?? p.proposed_sql ?? ''); setQuestion(p.question ?? ''); setResult(null); }, () => {});
  }, [seed]);

  const adopt = (p: any) => { setProposal(p); setSql(p.validated_sql ?? p.proposed_sql ?? sql); setResult(null); };
  const ask = useAction(async () => adopt(await request('POST', t('/queries/proposals'), { question })));
  const check = useAction(async () => adopt(await request('POST', t('/queries/proposals'), { sql, parent_id: proposal?.id })));
  const exec = useAction(async (mode: 'preview' | 'run') => {
    const id = crypto.randomUUID(); setExecId(id);
    try { setResult(await request('POST', t(`/queries/proposals/${proposal.id}/execute`), { mode, execution_id: id })); }
    finally { setExecId(null); }
  });
  const cancel = useAction(async () => { if (execId) await request('POST', t(`/queries/executions/${execId}/cancel`), {}); });
  const exportCsv = useAction(async () => { const r = await download('POST', t(`/queries/proposals/${proposal.id}/export`), {}); saveBlob(r.blob, r.filename); });
  const sqlChanged = proposal && sql !== (proposal.validated_sql ?? proposal.proposed_sql ?? '');
  const v = proposal?.validation;

  return (
    <Page title="Query workspace" sub="Ask a question or write SQL. Nothing runs until you execute it, and every run is re-validated under your current access.">
      <div className="split">
        <div className="stack">
          <Section title="Ask in plain language" hint={catalog.data ? `Generated by ${catalog.data.provider.id}${catalog.data.provider.model ? ` (${catalog.data.provider.model})` : ''}. Generation never executes.` : undefined}>
            <textarea rows={3} value={question} onChange={(e) => setQuestion(e.target.value)} placeholder="e.g. What is the total paid amount by claim status?" aria-label="Question" />
            <div><Button primary busy={ask.busy} disabled={!question.trim()} onClick={() => ask.run()}>Propose SQL</Button></div>
            <ErrorBox error={ask.error} />
          </Section>
          <Section title="Data you may query" hint="Tables and columns for your role. Masked columns are redacted in results.">
            <Async load={catalog}>{(c) => (<>
              {c.tables.map((tb: any) => (
                <details key={tb.name}><summary><strong>{tb.name}</strong> <span className="muted small">{tb.kind}</span></summary>
                  <p className="muted small">{tb.description}</p>
                  <Table rows={tb.columns} cols={[{ head: 'Column', cell: (x: any) => <span className="mono">{x.name}</span> }, { head: 'Type', cell: (x: any) => x.type }, { head: 'Access', cell: (x: any) => <Signal status={x.access} /> }]} />
                </details>))}
              {c.relationships?.length > 0 && <Json value={c.relationships.map((r: any) => `${r.from.table}.${r.from.column} → ${r.to.table}.${r.to.column}`)} label="Relationships" />}
              {c.metrics?.length > 0 && <Json value={c.metrics} label="Metric definitions" />}
            </>)}</Async>
          </Section>
        </div>
        <div className="stack">
          <Section title="SQL" actions={proposal && <><Signal status={proposal.executable ? 'ok' : 'failed'} label={proposal.executable ? 'executable' : 'not executable'} />{proposal.source && <Tag>{proposal.source}</Tag>}</>}>
            <textarea className="sql" rows={9} value={sql} onChange={(e) => setSql(e.target.value)} spellCheck={false} aria-label="SQL" placeholder="SELECT …" />
            <div className="row">
              <Button busy={check.busy} disabled={!sql.trim()} onClick={() => check.run()}>Validate</Button>
              <Button primary busy={exec.busy} disabled={!proposal?.executable || sqlChanged || !session.can('query:run')} title={sqlChanged ? 'Validate your edit first' : undefined} onClick={() => exec.run('preview')}>Preview</Button>
              <Button busy={exec.busy} disabled={!proposal?.executable || sqlChanged || !session.can('query:run')} onClick={() => exec.run('run')}>Run</Button>
              {execId && <Button danger onClick={() => cancel.run()}>Cancel</Button>}
              {session.can('query:export') && <Button busy={exportCsv.busy} disabled={!proposal?.executable || sqlChanged} onClick={() => exportCsv.run()}>Export CSV</Button>}
              {proposal && session.can('saved_query:write') && <Button disabled={!proposal.executable || sqlChanged} onClick={() => { window.location.hash = `/saved/new?proposal=${proposal.id}`; }} title="Save as a reusable query">Save as…</Button>}
            </div>
            {sqlChanged && <Note tone="warn">The SQL changed since it was validated. Validate again before running.</Note>}
            <ErrorBox error={check.error ?? exec.error ?? cancel.error ?? exportCsv.error} />
            {proposal?.model_explanation && <Note>{proposal.model_explanation}</Note>}
            {proposal?.assumptions?.length > 0 && <Note tone="info"><strong>Assumptions</strong><ul>{proposal.assumptions.map((a: string, i: number) => <li key={i}>{a}</li>)}</ul></Note>}
          </Section>
          {v && (
            <Section title="Validation">
              {v.ok ? <Note tone="good">Valid for your role. {proposal.estimate && <>Estimated about {count(Math.round(proposal.estimate.rows))} rows (cost {proposal.estimate.cost}).</>}</Note> : <Note tone="bad"><strong>Not executable</strong><ul>{v.issues.map((i: any, n: number) => <li key={n}><span className="mono">{i.code}</span>: {i.message}</li>)}</ul></Note>}
              {v.summary?.length > 0 && <ul>{v.summary.map((s: string, i: number) => <li key={i}>{s}</li>)}</ul>}
              {v.ok && <>
                <Table rows={v.output} cols={[{ head: 'Output column', cell: (o: any) => o.name }, { head: 'From', cell: (o: any) => o.table ? `${o.table}.${o.column}` : 'expression' }, { head: 'Redaction', cell: (o: any) => (o.masked ? <Signal status="masked" label={o.masked} /> : '') }]} />
                <Json value={{ tables: v.tables, columns: v.columns, joins: v.joins }} label="Tables, columns and joins used" /></>}
            </Section>)}
          {result && (
            <Section title="Result" hint={result.status === 'succeeded' ? `${count(result.row_count)} rows${result.truncated ? ' (truncated)' : ''} · ${ms(result.duration_ms)} · ${result.mode}` : undefined}>
              {result.error && <Note tone="bad"><strong>{result.error.message}</strong> <span className="mono">{result.error.code}</span></Note>}
              {result.status === 'succeeded' && <Grid columns={result.columns} rows={result.rows} />}
              <Facts items={[['Executed SQL (sha256)', <span className="mono">{result.executed_sql_sha256?.slice(0, 16)}</span>], ['Policy epoch', String(result.policy_epoch)]]} />
              {result.executed_sql && <Json value={result.executed_sql} label="Executed SQL" />}
            </Section>)}
        </div>
      </div>
    </Page>
  );
}
